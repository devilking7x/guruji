const STRINGS: Record<Lang, Strings> = { hi, mr };
const LANG_KEY = "guruji-lang";

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === "mr" ? "mr" : "hi";
  } catch {
    return "hi";
  }
}

interface LangCtx {
  lang: Lang;
  t: Strings;
  setLang: (l: Lang) => void;
}

const Ctx = createContext<LangCtx>({ lang: "hi", t: hi, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* storage unavailable — session-only switch */
    }
    // Tell the backend too (best-effort): it stores the language and
    // replies in Marathi/Hindi from then on. UI never waits on this.
    void persistLanguage(l);
  }, []);

  useEffect(() => {
    try {
      document.documentElement.lang = lang;
    } catch {
      /* ignore */
    }
  }, [lang]);

  return (
    <Ctx.Provider value={{ lang, t: STRINGS[lang], setLang }}>
      {children}
    </Ctx.Provider>
  );
}

export function useLang(): LangCtx {
  return useContext(Ctx);
}
